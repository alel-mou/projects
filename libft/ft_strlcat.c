#include "libft.h"

size_t	ft_strlcat(char *dst, const char *src, size_t size)
{
	size_t	dst_len;
	size_t	src_len;
	int		i;

	src_len = ft_strlen(src);
	if (!dst)
		return (src_len);
	dst_len = ft_strlen(dst);
	if (size <= dst_len)
		return (size + src_len);
	i = 0;
	while (src[dst_len] && dst_len < size - 1)
	{
		dst[dst_len] = src[i];
		i++;
	}
	return (dst_len + src_len);
}
